import uuid
from datetime import datetime
from sqlalchemy import Column, String, Integer, Float, DateTime, Text, ForeignKey, JSON, Boolean
from sqlalchemy.orm import relationship
from app.database import Base

def generate_uuid():
    return str(uuid.uuid4())

class User(Base):
    __tablename__ = "users"

    id = Column(String, primary_key=True, default=generate_uuid)
    email = Column(String, unique=True, index=True, nullable=True)
    name = Column(String, default="Learner")
    created_at = Column(DateTime, default=datetime.utcnow)

    sessions = relationship("LearningSession", back_populates="user", cascade="all, delete-orphan")

class LearningSession(Base):
    __tablename__ = "learning_sessions"

    id = Column(String, primary_key=True, default=generate_uuid)
    user_id = Column(String, ForeignKey("users.id"), nullable=True)
    topic = Column(String, index=True, nullable=False)
    level = Column(String, default="Intermediate") # Beginner, Intermediate, Advanced
    goal = Column(String, default="Understand fundamentals & application")
    status = Column(String, default="active") # active, completed
    is_demo = Column(Boolean, default=False)
    current_stage = Column(String, default="understand") # understand, connect, apply, explain, improve
    
    # Core Concept Summary generated by AI
    core_concept_summary = Column(Text, nullable=True)
    
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    user = relationship("User", back_populates="sessions")
    concepts = relationship("Concept", back_populates="session", cascade="all, delete-orphan")
    relationships = relationship("ConceptRelationship", back_populates="session", cascade="all, delete-orphan")
    challenges = relationship("Challenge", back_populates="session", cascade="all, delete-orphan")
    knowledge_gaps = relationship("KnowledgeGap", back_populates="session", cascade="all, delete-orphan")

class Concept(Base):
    __tablename__ = "concepts"

    id = Column(String, primary_key=True, default=generate_uuid)
    session_id = Column(String, ForeignKey("learning_sessions.id"), nullable=False)
    name = Column(String, index=True, nullable=False)
    category = Column(String, default="related") # main, prerequisite, related, application
    summary = Column(Text, nullable=False)
    
    # Progressive "Explain Like I'm Learning" levels
    depth_intuition = Column(Text, nullable=True)
    depth_mechanism = Column(Text, nullable=True)
    depth_technical = Column(Text, nullable=True)
    depth_example = Column(Text, nullable=True)
    
    why_it_matters = Column(Text, nullable=True)
    real_world_app = Column(Text, nullable=True)
    cross_domain_app = Column(Text, nullable=True)
    contrast_concept = Column(Text, nullable=True)
    
    mastery_score = Column(Float, default=0.0)
    created_at = Column(DateTime, default=datetime.utcnow)

    session = relationship("LearningSession", back_populates="concepts")

class ConceptRelationship(Base):
    __tablename__ = "concept_relationships"

    id = Column(String, primary_key=True, default=generate_uuid)
    session_id = Column(String, ForeignKey("learning_sessions.id"), nullable=False)
    source_concept = Column(String, nullable=False)
    target_concept = Column(String, nullable=False)
    relation_type = Column(String, nullable=False) # PREREQUISITE, CAUSES, DEPENDS_ON, RELATED_TO, CONTRASTS_WITH, APPLIED_IN
    explanation = Column(Text, nullable=True)

    session = relationship("LearningSession", back_populates="relationships")

class Challenge(Base):
    __tablename__ = "challenges"

    id = Column(String, primary_key=True, default=generate_uuid)
    session_id = Column(String, ForeignKey("learning_sessions.id"), nullable=False)
    concept_name = Column(String, nullable=False)
    scenario = Column(Text, nullable=False)
    task = Column(Text, nullable=False)
    challenge_type = Column(String, default="free_form") # free_form, scenario, debug, comparison
    difficulty = Column(String, default="intermediate") # basic, intermediate, advanced
    context = Column(Text, nullable=True)
    hints = Column(JSON, default=list) # List of graduated hints
    created_at = Column(DateTime, default=datetime.utcnow)

    session = relationship("LearningSession", back_populates="challenges")
    responses = relationship("StudentResponse", back_populates="challenge", cascade="all, delete-orphan")

class StudentResponse(Base):
    __tablename__ = "student_responses"

    id = Column(String, primary_key=True, default=generate_uuid)
    session_id = Column(String, ForeignKey("learning_sessions.id"), nullable=False)
    challenge_id = Column(String, ForeignKey("challenges.id"), nullable=False)
    user_input = Column(Text, nullable=False)
    response_time_seconds = Column(Integer, default=0)
    created_at = Column(DateTime, default=datetime.utcnow)

    challenge = relationship("Challenge", back_populates="responses")
    analysis = relationship("ReasoningAnalysis", back_populates="response", uselist=False, cascade="all, delete-orphan")

class ReasoningAnalysis(Base):
    __tablename__ = "reasoning_analyses"

    id = Column(String, primary_key=True, default=generate_uuid)
    response_id = Column(String, ForeignKey("student_responses.id"), nullable=False)
    
    understanding_level = Column(String, nullable=False) # complete, partial, superficial, misconception, missing_prerequisite
    score = Column(Float, nullable=False) # Overall score 0-100
    
    # Understanding Profile Radar Scores
    score_knowledge = Column(Float, default=70.0)
    score_connections = Column(Float, default=70.0)
    score_reasoning = Column(Float, default=70.0)
    score_application = Column(Float, default=70.0)
    score_explanation = Column(Float, default=70.0)
    
    concepts_understood = Column(JSON, default=list)
    missing_concepts = Column(JSON, default=list)
    misconceptions = Column(JSON, default=list)
    
    reasoning_quality = Column(String, default="developing") # exemplary, proficient, developing, initial
    feedback = Column(Text, nullable=False)
    next_learning_action = Column(String, default="next_challenge")
    adaptive_followup_prompt = Column(Text, nullable=True)
    
    created_at = Column(DateTime, default=datetime.utcnow)

    response = relationship("StudentResponse", back_populates="analysis")

class KnowledgeGap(Base):
    __tablename__ = "knowledge_gaps"

    id = Column(String, primary_key=True, default=generate_uuid)
    session_id = Column(String, ForeignKey("learning_sessions.id"), nullable=False)
    concept_name = Column(String, nullable=False)
    understanding_score = Column(Float, default=50.0)
    status = Column(String, default="needs_attention") # needs_attention, improving, mastered
    remediation_notes = Column(Text, nullable=True)
    last_updated = Column(DateTime, default=datetime.utcnow)

    session = relationship("LearningSession", back_populates="knowledge_gaps")
